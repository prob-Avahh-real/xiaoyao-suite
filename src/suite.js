export function buildSuite() {
  return MOVEMENTS_RAW.map((raw, index) => {
    const { notes, totalBeats } = expandPattern(raw.pattern, raw.gongMidi);
    const drones = (raw.drones || []).map((d) => ({
      midi: degreeToMidi(raw.gongMidi, d.degree, d.oct ?? 0),
      velocity: d.velocity ?? 0.1,
    }));
    const durationSec = (totalBeats * 60) / raw.tempo;
    return {
      id: raw.id,
      roman: raw.roman,
      title: raw.title,
      subtitle: raw.subtitle,
      section: raw.section,
      epigraph: raw.epigraph,
      mood: raw.mood,
      mode: raw.mode,
      modeLabel: raw.modeLabel,
      gongMidi: raw.gongMidi,
      tempo: raw.tempo,
      color: raw.color,
      ink: raw.ink,
      kind: raw.kind,
      melody: notes,
      drones,
      totalBeats,
      durationSec,
      index,
    };
  });
}

